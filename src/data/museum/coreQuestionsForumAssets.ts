import type {MuseumAssetRecord, MuseumAssetVariant} from './museumAssetTypes';

type ForumAssetInput = Omit<MuseumAssetRecord, 'variants'> & {
  scene: readonly [number, number];
  panel: readonly [number, number];
};

const variant = (
  id: string,
  kind: 'scene' | 'panel',
  size: readonly [number, number],
): MuseumAssetVariant => ({
  path: `assets/museum/core-questions-forum/${id}-${kind}.webp`,
  width: size[0],
  height: size[1],
});

const forumAsset = ({scene, panel, ...record}: ForumAssetInput): MuseumAssetRecord => ({
  ...record,
  variants: {
    scene: variant(record.id, 'scene', scene),
    panel: variant(record.id, 'panel', panel),
  },
});

