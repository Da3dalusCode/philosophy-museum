import type {MuseumAssetRecord, MuseumAssetVariant} from './museumAssetTypes';

type JusticeAssetInput = Omit<MuseumAssetRecord, 'variants'> & {
  scene: readonly [number, number];
  panel: readonly [number, number];
};

const variant = (
  id: string,
  kind: 'scene' | 'panel',
  size: readonly [number, number],
): MuseumAssetVariant => ({
  path: `assets/museum/justice-democratic-reason/${id}-${kind}.webp`,
  width: size[0],
  height: size[1],
});

const galleryAsset = ({scene, panel, ...record}: JusticeAssetInput): MuseumAssetRecord => ({
  ...record,
  variants: {
    scene: variant(record.id, 'scene', scene),
    panel: variant(record.id, 'panel', panel),
  },
});

