import type {MuseumAssetId, MuseumAssetRecord, MuseumAssetVariant} from './museumAssetTypes';

type GalleryAssetInput = Omit<MuseumAssetRecord, 'id' | 'variants'> & {
  id: string;
  scene: readonly [number, number];
  panel: readonly [number, number];
};

