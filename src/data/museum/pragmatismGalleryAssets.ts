const variant = (
  id: PragmatismGalleryAssetId,
  kind: 'scene' | 'panel',
  size: readonly [number, number],
): MuseumAssetVariant => ({
  path: `assets/museum/${folder}/${id}-${kind}.webp`,
  width: size[0],
  height: size[1],
});

const asset = ({
  id,
  rights,
  scene,
  panel,
  likenessStatus = 'not-applicable',
  ...input
}: AssetInput): MuseumAssetRecord => ({
  ...input,
  ...rights,
  id: id as MuseumAssetId,
  derivativeNotice,
  variants: {
    scene: variant(id, 'scene', scene),
    panel: variant(id, 'panel', panel),
  },
  likenessStatus,
});

